CREATE DATABASE IF NOT EXISTS db_kamus_daerah CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_kamus_daerah;

CREATE TABLE IF NOT EXISTS kamus_kata (
    id INT AUTO_INCREMENT PRIMARY KEY,
    indonesia VARCHAR(255) NOT NULL UNIQUE,
    tunjung VARCHAR(255) DEFAULT NULL,
    benuaq VARCHAR(255) DEFAULT NULL,
    kenyah VARCHAR(255) DEFAULT NULL,
    bahau VARCHAR(255) DEFAULT NULL,
    kutai VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_indonesia (indonesia)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
